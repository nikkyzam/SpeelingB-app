import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { createActivityClock } from '@/services/games/activityClock'
beforeEach(() => vi.useFakeTimers())
afterEach(() => vi.useRealTimers())

it('preserves the remaining delay across a long pause', () => {
  const clock = createActivityClock(), callback = vi.fn()
  clock.setTimeout(callback, 1000)
  vi.advanceTimersByTime(400)
  clock.setPaused(true)
  const now = clock.now()
  vi.advanceTimersByTime(60_000)
  expect(clock.now()).toBe(now)
  expect(callback).not.toHaveBeenCalled()
  clock.setPaused(false)
  vi.advanceTimersByTime(599)
  expect(callback).not.toHaveBeenCalled()
  vi.advanceTimersByTime(1)
  expect(callback).toHaveBeenCalledOnce()
})

it('pauses intervals and cancels timers even when they were created during a pause', () => {
  const clock = createActivityClock(), tick = vi.fn(), later = vi.fn()
  const interval = clock.setInterval(tick, 100)
  vi.advanceTimersByTime(250)
  expect(tick).toHaveBeenCalledTimes(2)
  clock.setPaused(true)
  const timeout = clock.setTimeout(later, 100)
  clock.clearTimeout(timeout)
  vi.advanceTimersByTime(10_000)
  expect(tick).toHaveBeenCalledTimes(2)
  clock.setPaused(false)
  vi.advanceTimersByTime(50)
  expect(tick).toHaveBeenCalledTimes(3)
  clock.clearInterval(interval)
  vi.advanceTimersByTime(1000)
  expect(tick).toHaveBeenCalledTimes(3)
  expect(later).not.toHaveBeenCalled()
})
